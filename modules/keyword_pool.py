def get_keywords_by_priority():
    """
    Возвращает все ключевые слова, отсортированные по приоритету.
    Сначала идёт техническая литература (приоритет 1), затем остальное.
    """
    sorted_groups = sorted(KEYWORD_POOL, key=lambda g: g["priority"])
    result = []
    for group in sorted_groups:
        for kw in group["keywords"]:
            if kw not in result:
                result.append(kw)
    return result


def get_keyword_groups():
    """
    Возвращает группы ключевых слов с метаданными.
    Используется для последовательного парсинга по тематикам.
    """
    return sorted(KEYWORD_POOL, key=lambda g: g["priority"])


def get_query_category_map():
    """
    Возвращает словарь {ключевое слово: категория}.
    Категория берётся из первой группы, где слово встретилось.
    """
    mapping = {}
    for group in get_keyword_groups():
        for kw in group["keywords"]:
            mapping.setdefault(kw, group["category"])
    return mapping
